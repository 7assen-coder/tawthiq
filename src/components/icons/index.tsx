export function getCasIcon(icon: string, size = 16, color = "currentColor") {
  switch (icon) {
    case "check": return <CheckIcon size={size} color={color} />;
    case "alert": return <AlertTriangleIcon size={size} color={color} />;
    case "flag": return <FlagIcon size={size} color={color} />;
    case "arrow-up": return <ArrowUpIcon size={size} color={color} />;
    case "x-circle": return <XCircleIcon size={size} color={color} />;
    default: return <CheckIcon size={size} color={color} />;
  }
}
